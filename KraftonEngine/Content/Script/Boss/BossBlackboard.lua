-- BossBlackboard.lua
-- 모든 수치 조절은 이 파일에서만 한다.
-- 개발 중 이 파일만 건드리면 BB 전체 수치가 반영된다.

local BB = {}

-- ── 체력 ─────────────────────────────────────
BB.MAX_HP = 100.0   -- 보스 최대 체력

-- ── 거리 임계값 ──────────────────────────────
BB.CHASE_DISTANCE  = 10.0   -- 이 이상이면 추격
BB.ATTACK_DISTANCE = 10.0   -- 이 이하이면 공격 가능

-- ── LookAt 회전 속도 (도/초) ─────────────────
BB.LOOK_AT_SPEED = 540.0   -- 너무 작으면 허공 칼질, 너무 크면 스냅

-- ── 글로벌 쿨타임 (패턴 종료 후 추가 대기) ───
BB.PATTERN_COOLDOWN = {
    AFTER_P1 = 1.3,   -- 패턴 간 숨 돌릴 틈 (연속 압박 완화)
    AFTER_P2 = 1.6,
    AFTER_P3 = 1.0,
}
BB.HEAVY_ATTACK_COOLDOWN = 8.0   -- P3 개별 쿨타임 (난사 방지)

-- ── 패턴 선택 확률 ───────────────────────────
BB.PROB_HEAVY  = 0.35   -- 패턴3(강공격) 선택 확률 — 길고 강하니 약간 낮춤
BB.PROB_DOUBLE = 0.35   -- 패턴2(2연타) 선택 확률 (누적: 0.35 + 0.35)
-- 나머지 0.30 → 패턴1(빠른 견제)

-- ── 슬로모 (공통) ────────────────────────────
-- 퍼펙트 회피 판정/슬로모 호출은 플레이어가 함 (회피 무적 중 피격 = 퍼펙트).
-- 보스는 OnSlomoStarted 알림을 받아 코루틴/쿨타임만 보정한다.
BB.PERFECT = {
    SLOMO_DURATION = 1.5,   -- 슬로우모션 지속 시간
    SLOMO_SCALE    = 0.1,   -- 타임스케일 (0.1 = 10% 속도)
}

-- ── 패턴 1: 단발 (heavy1, 애니 0.967s) — 옆으로 피하기
BB.P1 = {
    WINDUP = 0.40,   -- 장판 번쩍(경고)
    HIT    = 0.75,   -- 판정 — 경고~판정 0.35초 확보 (반응 가능)
    TOTAL  = 1.35,   -- 애니 + 후딜(반격 타임)
}

-- ── 패턴 2: 부채꼴 2연타 (heavy2~3, 애니 2.017s) — 뒤/타이밍 회피
-- HeavyCombo2: 0.000 ~ 1.050s / HeavyCombo3: 1.050 ~ 2.017s
BB.P2 = {
    HIT1        = 0.75,   -- 1타 판정 (HeavyCombo2 재생 중)
    SECOND_WIND = 1.05,   -- 2타 장판 스폰 (HeavyCombo3 시작 시점에 맞춤, 기존 1.15)
    HIT2        = 1.75,   -- 2타 판정 (HeavyCombo3 기준 0.70s 지점, 기존 1.80)
    TOTAL       = 3.5,   -- 애니 끝(2.017) + 후딜 0.48초
    FLASH_LEAD  = 0.35,   -- 번쩍~판정 0.35초
}

-- ── 패턴 3: 차오름 강타 (light3~4, 애니 2.017s) — 차오름 보고 회피
BB.P3 = {
    TRACK_END = 0.85,   -- 보스 회전 멈춤 (옆 공간 확보)
    FLASH     = 1.20,   -- 섬광 — 판정 0.35초 전 (1.40→1.20)
    HIT       = 1.55,   -- 판정 (차오름 1.55초 예고라 이미 여유)
    TOTAL     = 2.80,
}

-- ── 장판(텔레그래프) 연출 수치 ──────────────
BB.FEEDBACK = {
    -- 순수 흰색 데칼 머티리얼 — SetColorRGBA(=DecalColor)가 그대로 최종색이 됨.
    -- ZONE_COLOR_* 값이 텍스처 패턴 없이 깔끔한 단색 장판으로 표시된다.
    DECAL_MATERIAL = "Content/Material/VFX/M_WhiteZone.mat",

    -- P3 직사각형 장판 크기 (데칼 볼륨 OBB)
    ZONE_LENGTH   = 20.0,    -- 보스 앞으로 뻗는 길이
    ZONE_WIDTH    = 10,    -- 폭
    ZONE_HEIGHT   = 2.0,    -- 위아래 볼륨 (바닥 투영용)
    ZONE_Z_OFFSET = -2.5,   -- 보스 위치 기준 Z 보정 (발밑으로) — 띄워보고 조절

    -- 색 (R,G,B,A)
    ZONE_COLOR_IDLE  = { 1.0, 0.0, 0.0, 0.4 },   -- 평소 흐릿한 빨강
    ZONE_COLOR_FLASH = { 1.0, 0.0, 0.0, 0.9 },   -- 번쩍임 (진해짐)

    -- P1 종베기 장판 (좁은 직사각형 → 옆으로 피해야 회피 성공)
    P1_LENGTH = 20.0,   -- 보스 앞으로 뻗는 길이 (P3 8.0보다 짧게)
    P1_WIDTH  = 10,   -- 폭 (좁을수록 옆 회피 유도)

    -- P2 횡베기 부채꼴 장판 (가는 조각 N개를 방사형으로 펼침)
    FAN_ANGLE     = 55.0,   -- 총 중심각 (도) — 80→55, 좌우로 옆 회피 공간 확보
    FAN_SEGMENTS  = 10,      -- 조각 개수 (많을수록 매끈, 무거움)
    FAN_RADIUS    = 20.0,    -- 부채꼴 반지름 (조각 길이)
    FAN_SEG_WIDTH = 5,    -- 조각 폭 (인접 조각과 겹치게 넉넉히 → 빈틈 방지)

    -- 자동 페이드 방지용 큰 값 (HideZone 에서 직접 제거)
    NO_FADE_DELAY = 9999.0,
}

-- ── 디버그 ───────────────────────────────────
BB.DEBUG = true   -- false 로 바꾸면 print 전부 꺼짐

return BB
