-- BossBlackboard.lua
-- 모든 수치 조절은 이 파일에서만 한다.
-- 개발 중 이 파일만 건드리면 BB 전체 수치가 반영된다.

local BB = {}

-- ── 체력 ─────────────────────────────────────
BB.MAX_HP = 100.0   -- 보스 최대 체력

-- ── 거리 임계값 ──────────────────────────────
BB.CHASE_DISTANCE  = 10.0   -- 이 이상이면 추격
BB.ATTACK_DISTANCE = 7.0   -- 이 이하이면 공격 가능

-- ── LookAt 회전 속도 (도/초) ─────────────────
BB.LOOK_AT_SPEED = 540.0   -- 너무 작으면 허공 칼질, 너무 크면 스냅

-- ── 글로벌 쿨타임 (패턴 종료 후 추가 대기) ───
BB.PATTERN_COOLDOWN = {
    AFTER_P1 = 1.0,
    AFTER_P2 = 1.2,
    AFTER_P3 = 0.5,   -- P3는 후딜이 이미 길어서 짧게
}
BB.HEAVY_ATTACK_COOLDOWN = 8.0   -- P3 개별 쿨타임 (난사 방지)

-- ── 패턴 선택 확률 ───────────────────────────
BB.PROB_HEAVY  = 0.40   -- 패턴3 선택 확률 (HeavyAttackCooldown <= 0 일 때)
BB.PROB_DOUBLE = 0.30   -- 패턴2 선택 확률 (누적: 0.40 + 0.30)
-- 나머지 0.30 → 패턴1

-- ── 슬로모 (공통) ────────────────────────────
-- 퍼펙트 회피 판정/슬로모 호출은 플레이어가 함 (회피 무적 중 피격 = 퍼펙트).
-- 보스는 OnSlomoStarted 알림을 받아 코루틴/쿨타임만 보정한다.
-- 아래 값은 플레이어팀과 맞춘 기본값 (플레이어가 인자로 넘기면 그 값 우선).
BB.PERFECT = {
    SLOMO_DURATION = 1.5,   -- 슬로우모션 지속 시간
    SLOMO_SCALE    = 0.1,   -- 타임스케일 (0.1 = 10% 속도)
}

-- ── 패턴 1: 기본 베기 타임라인 ──────────────
BB.P1 = {
    WINDUP = 0.4,   -- 장판 번쩍임 (회피 가이드)
    HIT    = 0.5,   -- 데미지 판정 시점
    TOTAL  = 1.0,   -- 전체 지속 시간 (후딜 포함)
    DAMAGE = 10,
    HITSTOP = 0.04,
}

-- ── 패턴 2: 2연속 베기 타임라인 ─────────────
BB.P2 = {
    HIT1        = 0.4,   -- 1타 판정
    SECOND_WIND = 0.5,   -- 2타 예고선 표시
    HIT2        = 0.9,   -- 2타 판정
    TOTAL       = 1.8,   -- 전체 지속 시간
    FLASH_LEAD  = 0.15,  -- 각 타격 판정 몇 초 전에 번쩍일지 (회피 가이드)
    DAMAGE1     = 8,
    DAMAGE2     = 12,
    HITSTOP     = 0.04,
}

-- ── 패턴 3: 강한 내려찍기 타임라인 ──────────
BB.P3 = {
    TRACK_END = 0.8,    -- 플레이어 추적(보스 회전) 멈추는 시점
    FLASH     = 1.2,    -- 붉은 섬광 (회피 신호)
    HIT       = 1.4,    -- 데미지 판정 시점
    TOTAL     = 3.0,    -- 전체 지속 시간 (긴 후딜 포함)
    DAMAGE    = 25,
    HITSTOP   = 0.06,
}

-- ── 장판(텔레그래프) 연출 수치 ──────────────
BB.FEEDBACK = {
    -- 순수 흰색 데칼 머티리얼 — SetColorRGBA(=DecalColor)가 그대로 최종색이 됨.
    -- ZONE_COLOR_* 값이 텍스처 패턴 없이 깔끔한 단색 장판으로 표시된다.
    DECAL_MATERIAL = "Content/Material/VFX/M_WhiteZone.mat",

    -- P3 직사각형 장판 크기 (데칼 볼륨 OBB)
    ZONE_LENGTH   = 8.0,    -- 보스 앞으로 뻗는 길이
    ZONE_WIDTH    = 2.5,    -- 폭
    ZONE_HEIGHT   = 2.0,    -- 위아래 볼륨 (바닥 투영용)
    ZONE_Z_OFFSET = -2.5,   -- 보스 위치 기준 Z 보정 (발밑으로) — 띄워보고 조절

    -- 색 (R,G,B,A)
    ZONE_COLOR_IDLE  = { 1.0, 0.0, 0.0, 0.4 },   -- 평소 흐릿한 빨강
    ZONE_COLOR_FLASH = { 1.0, 0.0, 0.0, 0.9 },   -- 번쩍임 (진해짐)

    -- P1 종베기 장판 (좁은 직사각형 → 옆으로 피해야 회피 성공)
    P1_LENGTH = 5.0,   -- 보스 앞으로 뻗는 길이 (P3 8.0보다 짧게)
    P1_WIDTH  = 1.5,   -- 폭 (좁을수록 옆 회피 유도)

    -- P2 횡베기 부채꼴 장판 (가는 조각 N개를 방사형으로 펼침)
    FAN_ANGLE     = 80.0,   -- 총 중심각 (도) — 좌우로 넓게 휩쓸리는 느낌
    FAN_SEGMENTS  = 7,      -- 조각 개수 (많을수록 매끈, 무거움)
    FAN_RADIUS    = 6.0,    -- 부채꼴 반지름 (조각 길이)
    FAN_SEG_WIDTH = 1.6,    -- 조각 폭 (인접 조각과 겹치게 넉넉히 → 빈틈 방지)

    -- 자동 페이드 방지용 큰 값 (HideZone 에서 직접 제거)
    NO_FADE_DELAY = 9999.0,
}

-- ── 디버그 ───────────────────────────────────
BB.DEBUG = true   -- false 로 바꾸면 print 전부 꺼짐

return BB
